#!/usr/bin/env python3
# -*- coding: utf-8 -*-

# Fetches the QGIS Grant Programme blog posts from the RSS feed and writes one
# front matter only file per post in content/community/organisation/grants/.
# Hugo builds no page for a post: the grants list links straight to the blog.
# Existing files are overwritten on each run to reflect the latest source content.

import os
import re
import requests
import defusedxml.ElementTree as ET
from dateutil.parser import parse as date_parse
from bs4 import BeautifulSoup
from urllib.parse import unquote, urlparse

FEED_URL = "https://blog.qgis.org/category/grant-programme/index.xml"
GRANTS_FOLDER = "content/community/organisation/grants"
EXCERPT_WORDS = 20



def slug_from_url(url):
    """Derive a filesystem-safe slug from a blog post URL.

    The blog keeps "#" and "." in its slugs, so ".../qgis-grants-%2311-call/"
    becomes "qgis-grants-11-call".
    """
    path = unquote(urlparse(url).path.rstrip("/"))
    slug = re.sub(r"[^a-z0-9-]+", "-", os.path.basename(path).lower())
    return re.sub(r"-{2,}", "-", slug).strip("-")


def extract_description(raw_html):
    """Turn the HTML summary into a short plain text excerpt for the list page."""
    words = BeautifulSoup(raw_html, "html.parser").get_text().split()
    if len(words) <= EXCERPT_WORDS:
        return " ".join(words)
    return " ".join(words[:EXCERPT_WORDS]) + "…"


def fetch_grants():
    os.makedirs(GRANTS_FOLDER, exist_ok=True)

    response = requests.get(FEED_URL)
    response.raise_for_status()

    root = ET.fromstring(response.content)
    channel = root.find("channel")

    for item in channel.findall("item"):
        title = (item.findtext("title") or "").strip()
        link = (item.findtext("link") or "").strip()
        pub_date_str = (item.findtext("pubDate") or "").strip()
        summary_html = (item.findtext("description") or "").strip()

        slug = slug_from_url(link)
        if not title or not slug:
            continue

        try:
            pub_date = date_parse(pub_date_str).strftime("%Y-%m-%d")
        except Exception:
            pub_date = pub_date_str

        markdown_filename = os.path.join(GRANTS_FOLDER, f"{slug}.md")

        description = extract_description(summary_html)
        escaped_title = title.replace('"', '\\"')
        escaped_description = description.replace('"', '\\"')

        md_content = (
            "---\n"
            "# \u26a0\ufe0f  AUTOMATED FILE - DO NOT EDIT MANUALLY!\n"
            "# Generated by: scripts/fetch_grants.py\n"
            f"# Source: {link}\n"
            "# To update: Run 'scripts/fetch_grants.py' (automated nightly via GitHub Actions)\n"
            "# See CONTRIBUTING.md section: Automated Content and Manual Edit Guidelines\n"
            "\n"
            f'title: "{escaped_title}"\n'
            f'date: "{pub_date}"\n'
            f'description: "{escaped_description}"\n'
            f'externalLink: "{link}"\n'
            "build:\n"
            "  render: link\n"
            "  list: local\n"
            "---\n"
        )

        with open(markdown_filename, "w", encoding="utf-8") as f:
            f.write(md_content)
            print(f"Writing: {markdown_filename}")


if __name__ == "__main__":
    fetch_grants()
